//! The C reference TPMs' random-number generation (`reference-rng` feature): [`ReferenceRng`],
//! a [`tpm2::crypto::Rng`] that is the reference's own DRBG, and
//! [`ReferenceCryptoProvider`](crate::ReferenceCryptoProvider), the BoringSSL backend on it.
//!
//! A TPM whose crypto backend draws from [`ReferenceRng`] draws the same random bytes as the TCG
//! reference implementation (`tcgtpm`) and the IBM software TPM (`ibmswtpm2`, whose RNG code is
//! the same); the random algorithms that consume them (the RSA encodings of `tpm2::crypto`, the
//! key generations and ECC signatures of `tpm2_engine::asymmetric`) draw in the reference's order
//! and sizes, so the TPM produces exactly the same keys, nonces, signatures and ciphertexts as
//! the C references, which lets the differential tests compare them byte for byte.
//!
//! The DRBG is the reference's own, unmodified C code, linked into this crate: `build.rs`
//! compiles the `tcgtpm` sources, at the commit and with the profile patches the differential
//! tests use, into a symbol-isolated static library; there is no hand-written C, all glue is Rust
//! (the private `ffi` module, with types generated by `bindgen` from the reference headers):
//!
//! - `drbg`: the CTR-DRBG of `CryptRand.c` (`DRBG_Instantiate()`, `DRBG_Reseed()`,
//!   `DRBG_Generate()`, `DRBG_SelfTest()`, `CryptRandStartup()`, `CryptRandomStir()`,
//!   `DRBG_InstantiateSeeded()`, `DRBG_AdditionalData()`), seeded from the platform entropy
//!   source;
//! - the test oracles `rsa` (`CryptRsaGenerateKey()` with the prime sieve and Miller-Rabin of
//!   `CryptPrime.c`/`CryptPrimeSieve.c`, and the encodings `OaepEncode()`,
//!   `RSAES_PKCS1v1_5Encode()` and `PssEncode()` of `CryptRsa.c`) and `ecc`
//!   (`CryptEccGenerateKey()`, `CryptEccNewKeyPair()`, `CryptEccSign()`: ECDSA, SM2 and
//!   EC-Schnorr), against which the tests check that the Rust algorithms draw and produce
//!   exactly what the reference's do from the same DRBG state (`oracles.rs`).
//!
//! All `unsafe` code of the crate is in the private `ffi` module, which wraps the C entry points
//! in safe functions and implements the platform functions the C code calls. The reference keeps
//! the TPM's DRBG and its other RNG state in globals; these are redirected at compile time to
//! accessors in `ffi` that return the state of the current call, which lives on the calling Rust
//! function's stack (loaded from and stored back to the [`ReferenceRng`] the call is made with)
//! and is found through POSIX thread-local storage, so any number of TPMs can use the C code
//! concurrently. The C code's big-number arithmetic (TpmBigNum on OpenSSL) is not constant time;
//! this feature is meant for differential testing, not for production.
//!
//! The C code is compiled with SHA-512 exactly when this crate's `sha512` feature is enabled,
//! which must therefore match the `sha512` feature of the `tpm2` the TPM is built with (every
//! crate of the workspace forwards its `sha512` feature to its dependencies).

