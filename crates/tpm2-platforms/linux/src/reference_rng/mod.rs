use crate::{LinuxRng, ReferenceEntropy};

/// The size of the DRBG's persistent state (`DRBG_STATE`, the NV image of `go.drbgState`,
/// [`DrbgState::to_bytes`]).
const STATE_SIZE: usize = tpm2_engine::DRBG_STATE_SIZE;

/// The platform entropy source of the TPM's DRBG (the reference's `_plat__GetEntropy()`, called
/// by `DRBG_GetEntropy()`), as seen by the linked C code.
pub(crate) trait EntropySource {
    /// Fills `out` completely with entropy, or fails (an entropy failure of the reference).
    fn fill(&mut self, out: &mut [u8]) -> Result<(), CryptoError>;
}

impl EntropySource for ReferenceEntropy {
    fn fill(&mut self, out: &mut [u8]) -> Result<(), CryptoError> {
        ReferenceEntropy::fill(self, out)
    }
}

impl EntropySource for LinuxRng {
    fn fill(&mut self, out: &mut [u8]) -> Result<(), CryptoError> {
        self.fill_bytes(out)
    }
}

/// The state of the reference code that one call of a C entry point uses (see `ffi`): the TPM's
/// DRBG (`drbgDefault`, i.e. `go.drbgState`), its platform entropy source and its self-test
/// flags (`g_cryptoSelfTestState.rng`). A missing DRBG or entropy source makes the C code fail
/// when it needs it; without flags, the calls share a process-wide `TESTED` flag.
pub(crate) struct RefRng<'a> {
    /// The TPM's DRBG, if any.
    pub drbg: Option<&'a mut DrbgState>,
    /// The platform entropy source, if any.
    pub entropy: Option<&'a mut dyn EntropySource>,
    /// The DRBG self-test flags (`TESTED`, `ENTROPY`) of the TPM's DRBG, if any.
    pub flags: Option<&'a mut u32>,
}

impl RefRng<'static> {
    /// A context without the TPM's DRBG, its entropy source and its flags, for calls that draw
    /// only from a seeded DRBG.
    pub fn seeded_only() -> Self {
        Self {
            drbg: None,
            entropy: None,
            flags: None,
        }
    }
}

/// The platform entropy source of a [`ReferenceRng`] that is the TPM's DRBG.
enum Entropy {
    /// The C reference TPMs' simulator-platform entropy source.
    Reference(ReferenceEntropy),
    /// The OS entropy source.
    Os(LinuxRng),
}

impl Entropy {
    /// The entropy source as the C code sees it.
    fn source(&mut self) -> &mut dyn EntropySource {
        match self {
            Self::Reference(entropy) => entropy,
            Self::Os(entropy) => entropy,
        }
    }
}

/// What a [`ReferenceRng`] is.
enum Kind {
    /// The TPM's DRBG (`drbgDefault`), with its entropy source and its DRBG self-test flags.
    Tpm { entropy: Entropy, flags: u32 },
    /// A deterministic DRBG (`DRBG_InstantiateSeeded()`), which never draws entropy.
    Seeded,
}

/// The C reference TPMs' random number generator, linked from their original C code (compiled
/// by `build.rs` from the unmodified `tcgtpm` sources, see the `reference-rng` feature): either the TPM's DRBG (`drbgDefault`, the `crypto_rng` of a
/// TPM), seeded from a platform entropy source ([`ReferenceRng::new`],
/// [`Random::from_entropy`]), or a deterministic DRBG for Primary Objects
/// ([`Random::instantiate_seeded`], [`Random::from_seed`]).
///
/// It implements [`Rng`] (random bytes and the DRBG lifecycle and state hooks; an RNG implements
/// no random algorithm) with the reference's C functions on this DRBG:
///
/// | [`Rng`] method | The TPM's DRBG | A seeded DRBG |
/// |---|---|---|
/// | [`fill_bytes`](Rng::fill_bytes) | `DRBG_Generate(NULL, ...)` | `DRBG_Generate(state, ...)` |
/// | [`stir_bytes`](Rng::stir_bytes) | `CryptRandomStir()` | `DRBG_AdditionalData()` |
/// | [`init`](Rng::init) | `_plat__GetEntropy(NULL, 0)` ([`ReferenceEntropy::init`]) | nothing |
/// | [`startup`](Rng::startup) | `CryptRandStartup()` | nothing |
/// | [`self_test`](Rng::self_test) | `DRBG_SelfTest()` (clearing the flags first) | `DRBG_SelfTest()` |
/// | [`save_state`](Rng::save_state) / [`load_state`](Rng::load_state) | `DRBG_STATE` ([`DrbgState::to_bytes`]) | the same |
///
/// It is not the backend's system RNG ([`Rng::is_system_rng`] is `false`), so `tpm2-engine`
/// generates keys and signs with the reference's algorithms on it (`tpm2_engine::asymmetric`).
///
/// The TPM's DRBG keeps its DRBG self-test flags (`g_cryptoSelfTestState.rng`: `TESTED` once
/// `DRBG_SelfTest()` has passed, `ENTROPY` once the entropy source has failed) itself; they are
/// cleared by [`Rng::self_test`] (at `_TPM_Init`). Reference errors are reported as
/// [`CryptoError::Unsupported`] for unsupported parameters (`TPM_RC_VALUE`, `TPM_RC_RANGE`,
/// `TPM_RC_CURVE`, `TPM_RC_SIZE`, `TPM_RC_HASH`; e.g. stirred data larger than the reference's
/// buffers) and as [`CryptoError::Internal`] otherwise (e.g. `TPM_RC_FAILURE`: an entropy
/// failure, an uninstantiated DRBG or a seeded DRBG that needs reseeding).
///
/// A method called from the entropy source of a running call (on the same thread) fails; a panic
/// in the entropy source aborts the process (it cannot unwind through C).
pub struct ReferenceRng {
    /// The DRBG's state (`DRBG_STATE`).
    drbg: DrbgState,
    /// The TPM's DRBG or a seeded DRBG.
    kind: Kind,
}

impl ReferenceRng {
    /// The TPM's DRBG of a C reference TPM process (`drbgDefault`) on the entropy source
    /// `entropy` of that process, not instantiated yet: [`Rng::startup`] (`CryptRandStartup()`)
    /// instantiates it, unless [`Rng::load_state`] restores an instantiated state first. Creating
    /// it draws nothing, so that a TPM using it draws exactly what the reference process draws.
    pub fn new(entropy: ReferenceEntropy) -> Self {
        Self::tpm(Entropy::Reference(entropy))
    }

    /// The TPM's DRBG on the OS entropy source ([`LinuxRng`]), not instantiated yet (see
    /// [`ReferenceRng::new`]).
    pub fn with_os_entropy() -> Self {
        Self::tpm(Entropy::Os(LinuxRng::new()))
    }

    /// The TPM's DRBG on `entropy`, not instantiated.
    fn tpm(entropy: Entropy) -> Self {
        Self {
            drbg: DrbgState::default(),
            kind: Kind::Tpm { entropy, flags: 0 },
        }
    }

    /// A deterministic DRBG with the state `drbg`.
    fn seeded(drbg: DrbgState) -> Self {
        Self {
            drbg,
            kind: Kind::Seeded,
        }
    }

    /// Whether this is a deterministic DRBG ([`Random::instantiate_seeded`],
    /// [`Random::from_seed`]) rather than the TPM's DRBG.
    pub fn is_seeded(&self) -> bool {
        matches!(self.kind, Kind::Seeded)
    }

    /// Whether the DRBG is instantiated (`DRBG_STATE.magic == DRBG_MAGIC`).
    pub fn is_instantiated(&self) -> bool {
        self.drbg.magic == tpm2_engine::DRBG_MAGIC
    }

    /// Runs `f` with the call context and the `RAND_STATE` argument of a C entry point that
    /// draws from this DRBG: for the TPM's DRBG, a context with this DRBG as `drbgDefault`
    /// (with the entropy source and the flags) and no `RAND_STATE` (`NULL`); for a seeded DRBG,
    /// a context without the TPM's DRBG and this DRBG as the `RAND_STATE`.
    fn with_drbg<T>(&mut self, f: impl FnOnce(&mut RefRng<'_>, Option<&mut DrbgState>) -> T) -> T {
        match &mut self.kind {
            Kind::Tpm { entropy, flags } => {
                let mut rng = RefRng {
                    drbg: Some(&mut self.drbg),
                    entropy: Some(entropy.source()),
                    flags: Some(flags),
                };
                f(&mut rng, None)
            }
            Kind::Seeded => f(&mut RefRng::seeded_only(), Some(&mut self.drbg)),
        }
    }
}

/// Converts an error of the reference code (see [`ReferenceRng`]).
fn crypto_error(rc: TpmRc) -> CryptoError {
    if rc == TpmRc::VALUE
        || rc == TpmRc::RANGE
        || rc == TpmRc::CURVE
        || rc == TpmRc::SIZE
        || rc == TpmRc::HASH
    {
        CryptoError::Unsupported
    } else {
        CryptoError::Internal
    }
}

impl Random for ReferenceRng {
    type Rng = Self;

    /// The TPM's DRBG on the OS entropy source, instantiated (`DRBG_Instantiate()`, which runs
    /// the DRBG self test first).
    fn from_entropy() -> Result<Self, CryptoError> {
        let mut rng = Self::with_os_entropy();
        rng.with_drbg(|rng, _| drbg::instantiate(rng))
            .map_err(crypto_error)?;
        Ok(rng)
    }

    /// `DRBG_InstantiateSeeded(seed, "", "", "")`.
    fn from_seed(seed: &[u8]) -> Result<Self, CryptoError> {
        Self::instantiate_seeded(seed, &[], &[], &[])
    }

    /// `DRBG_InstantiateSeeded(seed, purpose, name, additional)`: each input at most 1024 bytes
    /// ([`CryptoError::Unsupported`] otherwise).
    fn instantiate_seeded(
        seed: &[u8],
        purpose: &[u8],
        name: &[u8],
        additional: &[u8],
    ) -> Result<Self, CryptoError> {
        drbg::instantiate_seeded(seed, purpose, name, additional)
            .map(Self::seeded)
            .map_err(crypto_error)
    }
}

impl Rng for ReferenceRng {
    const STATE_SIZE: usize = STATE_SIZE;

    /// `DRBG_Generate()`, failing unless all of `out` (at most `u16::MAX` bytes, the reference's
    /// request size) was filled.
    fn fill_bytes(&mut self, out: &mut [u8]) -> Result<(), CryptoError> {
        self.with_drbg(|rng, rand| drbg::fill(rng, rand, out))
            .map_err(crypto_error)
    }

    /// `CryptRandomStir()` for the TPM's DRBG (`TPM2_StirRandom`: a reseed with fresh entropy and
    /// `data`), `DRBG_AdditionalData()` for a seeded DRBG (`data` is mixed in deterministically;
    /// at most 1024 bytes).
    fn stir_bytes(&mut self, data: &[u8]) -> Result<(), CryptoError> {
        if self.is_seeded() {
            drbg::additional_data(&mut self.drbg, data)
        } else {
            self.with_drbg(|rng, _| drbg::stir(rng, data))
        }
        .map_err(crypto_error)
    }

    /// `_plat__GetEntropy(NULL, 0)` of the reference entropy source ([`ReferenceEntropy::init`]),
    /// which seeds it from the process ID and the real time; nothing otherwise.
    fn init(&mut self) -> Result<(), CryptoError> {
        if let Kind::Tpm {
            entropy: Entropy::Reference(entropy),
            ..
        } = &mut self.kind
        {
            entropy.init();
        }
        Ok(())
    }

    /// `CryptRandStartup()` for the TPM's DRBG: reseeds it with fresh entropy if it is
    /// instantiated, and instantiates it otherwise. Nothing for a seeded DRBG.
    fn startup(&mut self) -> Result<(), CryptoError> {
        match self.kind {
            Kind::Tpm { .. } => self
                .with_drbg(|rng, _| drbg::startup(rng))
                .map_err(crypto_error),
            Kind::Seeded => Ok(()),
        }
    }

    /// `DRBG_SelfTest()` (the DRBG's known-answer test on the NIST test vectors, which draws
    /// neither entropy nor from this DRBG). For the TPM's DRBG, the DRBG self-test flags are
    /// cleared first and the test sets `TESTED` if it passes.
    fn self_test(&mut self) -> Result<bool, CryptoError> {
        if let Kind::Tpm { flags, .. } = &mut self.kind {
            *flags = 0;
        }
        self.with_drbg(|rng, _| drbg::self_test(rng))
            .map_err(crypto_error)
    }

    fn save_state(&self, out: &mut [u8]) -> Result<(), CryptoError> {
        let state: [u8; STATE_SIZE] = self.drbg.to_bytes();
        out.get_mut(..STATE_SIZE)
            .ok_or(CryptoError::Internal)?
            .copy_from_slice(&state);
        Ok(())
    }

    fn load_state(&mut self, state: &[u8]) -> Result<(), CryptoError> {
        let state = state
            .get(..STATE_SIZE)
            .and_then(|s| s.try_into().ok())
            .ok_or(CryptoError::Internal)?;
        self.drbg = DrbgState::from_bytes(state);
        Ok(())
    }
}
