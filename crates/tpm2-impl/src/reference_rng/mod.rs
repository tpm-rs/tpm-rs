//! The C reference TPMs' random-number generation (`reference-rng` feature).
//!
//! With this feature, every random value `tpm-rs` produces is drawn the way the TCG reference
//! implementation (`mstpm20`) and the IBM software TPM (`ibmswtpm2`, whose RNG code is the same)
//! draw it: by the reference's own, unmodified C code, linked into this crate. `build.rs` compiles
//! the `mstpm20` sources, at the commit and with the profile patches the differential tests use,
//! into a symbol-isolated static library; there is no hand-written C, all glue is Rust (the
//! private `ffi` module, with types generated by `bindgen` from the reference headers):
//!
//! - [`drbg`]: the CTR-DRBG of `CryptRand.c` (`DRBG_Instantiate()`, `DRBG_Reseed()`,
//!   `DRBG_Generate()`, `CryptRandStartup()`, `CryptRandomStir()`,
//!   `DRBG_InstantiateSeeded()`, `DRBG_AdditionalData()`), seeded from the platform entropy
//!   source;
//! - [`rsa`]: RSA key generation (`CryptRsaGenerateKey()` with the prime sieve and Miller-Rabin of
//!   `CryptPrime.c`/`CryptPrimeSieve.c`) and the randomized encodings `OaepEncode()`,
//!   `RSAES_PKCS1v1_5Encode()` and `PssEncode()` of `CryptRsa.c`;
//! - [`ecc`]: ECC key generation (`CryptEccGenerateKey()`, `CryptEccNewKeyPair()`, i.e.
//!   `TpmEcc_GenPrivateScalar()` and the FIPS pairwise test) and ECDSA signing
//!   (`TpmEcc_SignEcdsa()`).
//!
//! Given the same platform entropy (see `tpm2_platform_linux::LinuxRng::reference`), `tpm-rs`
//! therefore produces exactly the same keys, nonces, signatures and ciphertexts as the C
//! references, which lets the differential tests compare them byte for byte.
//!
//! All `unsafe` code of the crate is in the private `ffi` module, which wraps the C entry points
//! in safe functions and implements the platform functions the C code calls. The reference keeps
//! the TPM's DRBG and its other RNG state in globals; these are redirected at compile time to
//! accessors in `ffi` that return the state of the current call, which lives on the calling Rust
//! function's stack (loaded from and stored back to the [`RefRng`] the call is made with) and is
//! found through POSIX thread-local storage, so any number of TPMs can use the C code
//! concurrently. The C code's big-number arithmetic (TpmBigNum on OpenSSL) is not constant time;
//! this feature is meant for differential testing, not for production.
//!
//! In every function with a `rand: Option<&mut DrbgState>` argument, `rand` selects the DRBG to
//! draw from, like the reference code's `RAND_STATE* rand` argument: `None` for the TPM's own
//! DRBG ([`RefRng::drbg`], `drbgDefault`), or a deterministic DRBG from
//! [`drbg::instantiate_seeded`] (the DRBG of a Primary Object).

pub mod drbg;
pub mod ecc;
mod ffi;
pub mod rsa;
#[cfg(test)]
mod vectors;

use tpm2::crypto::Rng;

use crate::engine::DrbgState;

/// The TPM a reference RNG call is made for: its own DRBG and the entropy source that DRBG is
/// instantiated and reseeded from.
pub struct RefRng<'a> {
    /// The TPM's own DRBG (`drbgDefault`, persisted in NV as `go.drbgState`), or `None` if there
    /// is none (then every use of it fails with `TPM_RC_FAILURE`).
    pub drbg: Option<&'a mut DrbgState>,
    /// The platform entropy source (`_plat__GetEntropy()`), or `None` for a failing one. It must
    /// not call back into this module (such calls fail with `TPM_RC_FAILURE`).
    pub entropy: Option<&'a mut dyn Rng>,
}

impl RefRng<'_> {
    /// A context without a TPM DRBG or entropy source, for drawing from seeded DRBGs only.
    pub fn seeded_only() -> RefRng<'static> {
        RefRng {
            drbg: None,
            entropy: None,
        }
    }
}
