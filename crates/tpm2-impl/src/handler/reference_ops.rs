//! Object creation and random asymmetric operations with the `reference-rng` feature.
//!
//! These are the counterparts of the reference code's `CryptCreateObject()`,
//! `CryptEccNewKeyPair()`, `TpmEcc_SignEcdsa()` (with `rand = NULL`) and the randomized RSA
//! encodings, on the reference's own C code linked by [`crate::reference_rng`]: they draw exactly
//! the random values the C reference TPMs draw, in the same order, from the same `RAND_STATE`
//! (the TPM's DRBG, or the DRBG seeded from a hierarchy's Primary Seed for Primary Objects). The
//! raw RSA operations on the padded blocks use the crypto provider, which holds the private keys.

use tpm2::Marshal;
use tpm2::crypto::{CryptoProvider, Rng};
use tpm2::errors::{Position, TpmRc};
use tpm2::{TpmEccCurve, TpmaObject, TpmiAlgHash, TpmtKeyedHashScheme, TpmtPublic};

use crate::engine::DrbgState;
use crate::handler::CommandHandler;
use crate::owned::{OwnedDigest, OwnedEccPoint, OwnedPublicParmsAndId, OwnedTpm2b};
use crate::reference_rng::{RefRng, drbg, ecc, rsa};
use crate::storage::NvStorage;
use crate::timer::TpmTimer;

/// `PRIMARY_OBJECT_CREATION`: the DRBG purpose of Primary Objects, with its terminating NUL.
const PRIMARY_OBJECT_CREATION: &[u8] = b"Primary Object Creation\0";

/// The Primary Seed context of a Primary Object being created.
pub(crate) struct PrimaryCreation<'p> {
    /// The hierarchy's Primary Seed (`HierarchyGetPrimarySeed()`).
    pub seed: &'p [u8],
    /// Whether the object is created in the endorsement hierarchy (`epsHierarchy`).
    pub endorsement: bool,
}

impl<'a, 'b, C: CryptoProvider, S: NvStorage, T: TpmTimer, R: Rng + Sync>
    CommandHandler<'a, 'b, C, S, T, R>
{
    /// `TpmEcc_SignEcdsa()` with the TPM's DRBG: signs `digest` with the private scalar `d`
    /// (big-endian) on `curve`, writing `r` and `s` (each padded to the order size) into
    /// `r_out`/`s_out`. Returns the order size.
    pub(crate) fn reference_ecdsa_sign(
        &mut self,
        curve: TpmEccCurve,
        d: &[u8],
        digest: &[u8],
        r_out: &mut [u8],
        s_out: &mut [u8],
    ) -> Result<usize, TpmRc> {
        ecc::sign_ecdsa(
            &mut self.context.ref_rng(),
            None,
            curve,
            d,
            digest,
            r_out,
            s_out,
        )
    }

    /// `CryptEccNewKeyPair()`: an ephemeral key pair from the TPM's DRBG (ECDH_KeyGen and
    /// `CryptSecretEncrypt()` for ECC keys). Writes `d` (padded to the coordinate size) into
    /// `d_out` and `x || y` into `q_out`, and returns the coordinate size.
    pub(crate) fn reference_ecc_new_key_pair(
        &mut self,
        curve: TpmEccCurve,
        d_out: &mut [u8],
        q_out: &mut [u8],
    ) -> Result<usize, TpmRc> {
        ecc::new_key_pair(&mut self.context.ref_rng(), curve, d_out, q_out)
    }

    /// The FIPS pairwise consistency test of `CryptEccGenerateKey()` for a signing key that was
    /// not generated by [`Self::reference_create_object`] (a Derived Object): signs a random
    /// digest (`min(key size, 64)` bytes) with ECDSA, both drawn from the TPM's DRBG. Only the
    /// random draws matter for the TPM's state.
    pub(crate) fn reference_ecc_pairwise_test(
        &mut self,
        curve: TpmEccCurve,
        d: &[u8],
    ) -> Result<(), TpmRc> {
        ecc::pairwise_test(&mut self.context.ref_rng(), curve, d)
    }

    /// `CryptCreateObject()`: generates the sensitive area of a new ordinary object (from the
    /// TPM's DRBG) or Primary Object (`primary`, from `DRBG_InstantiateSeeded(seed,
    /// PRIMARY_OBJECT_CREATION, template Name, inSensitive.data)`).
    ///
    /// Generates the key (RSA, ECC, or a TPM-generated SYMCIPHER/KEYEDHASH key when no data is
    /// supplied or `sensitiveDataOrigin` is SET), mixes in the endorsement hierarchy proofs for
    /// endorsement Primary Objects, draws the `seedValue` (one `nameAlg` digest) and computes the
    /// public `unique` field. Writes the private key (the crypto provider's format for RSA) to
    /// `private_key` and the `seedValue` to `seed`, and returns `(seed length, key length)`.
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn reference_create_object(
        &mut self,
        primary: Option<PrimaryCreation<'_>>,
        template: &TpmtPublic,
        sensitive_data: &[u8],
        parms_and_id: &mut OwnedPublicParmsAndId,
        private_key: &mut [u8],
        seed: &mut [u8; 64],
    ) -> Result<(usize, usize), TpmRc> {
        let name_alg = template
            .name_alg
            .ok_or(TpmRc::HASH.with(Position::parameter(2)))?;
        let attributes = template.object_attributes;
        let mut seeded: Option<DrbgState> = match &primary {
            Some(p) => {
                let mut buf = [0u8; tpm2::TpmtPublic::MAX_SIZE];
                let len = template.marshal(&mut buf);
                let template_name = self.compute_name(Some(name_alg), &buf[..len])?;
                Some(drbg::instantiate_seeded(
                    p.seed,
                    PRIMARY_OBJECT_CREATION,
                    template_name.get_buffer(),
                    sensitive_data,
                )?)
            }
            None => None,
        };
        let data = if attributes.contains(TpmaObject::SENSITIVE_DATA_ORIGIN) {
            &[][..]
        } else {
            sensitive_data
        };
        let sign = attributes.contains(TpmaObject::SIGN_ENCRYPT);

        // `DRBG_AdditionalData()` input of endorsement Primary Objects: shProof and ehProof.
        let endorsement_proofs = match &primary {
            Some(p) if p.endorsement => {
                let state = &self.context.state;
                let (mut sh, mut eh) = ([0u8; 64], [0u8; 64]);
                let sh_len = usize::from(state.sh_proof_size).min(64);
                let eh_len = usize::from(state.eh_proof_size).min(64);
                sh[..sh_len].copy_from_slice(&state.sh_proof[..sh_len]);
                eh[..eh_len].copy_from_slice(&state.eh_proof[..eh_len]);
                Some(((sh, sh_len), (eh, eh_len)))
            }
            _ => None,
        };

        // The key and `seedValue` are drawn from the Primary Object DRBG (`seeded`) or the TPM's
        // DRBG (`None`); the pairwise test of an ECC signing key always draws from the TPM's DRBG.
        let (key_len, seed_len) = {
            let engine = &mut *self.context;
            let crypto = &*engine.platform.crypto;
            let mut rng = RefRng {
                drbg: Some(&mut engine.state.drbg_state),
                entropy: Some(&mut *engine.platform.rng),
            };
            let key_len = match parms_and_id {
                OwnedPublicParmsAndId::Rsa(parms, unique) => {
                    let n_len = usize::from(parms.key_bits.0) / 8;
                    let mut n = [0u8; 512];
                    let mut p = [0u8; 256];
                    let n = n.get_mut(..n_len).ok_or(TpmRc::FAILURE)?;
                    let p = p.get_mut(..n_len / 2).ok_or(TpmRc::FAILURE)?;
                    let exponent = rsa::generate_key(
                        &mut rng,
                        seeded.as_mut(),
                        parms.key_bits.0,
                        parms.exponent,
                        sign,
                        n,
                        p,
                    )?;
                    *unique = OwnedTpm2b::from_bytes(n).map_err(|_| TpmRc::FAILURE)?;
                    crypto
                        .rsa_import_private_key(n, p, exponent, private_key)
                        .map_err(|_| TpmRc::FAILURE)?
                        .ok_or(TpmRc::FAILURE)?
                }
                OwnedPublicParmsAndId::Ecc(parms, point) => {
                    let mut q = [0u8; 2 * 66];
                    let len = ecc::generate_key(
                        &mut rng,
                        seeded.as_mut(),
                        parms.curve_id,
                        sign,
                        private_key,
                        &mut q,
                    )?;
                    *point = OwnedEccPoint {
                        x: OwnedTpm2b::from_bytes(&q[..len]).map_err(|_| TpmRc::FAILURE)?,
                        y: OwnedTpm2b::from_bytes(&q[len..2 * len]).map_err(|_| TpmRc::FAILURE)?,
                    };
                    len
                }
                OwnedPublicParmsAndId::Sym(sym_def, _) => {
                    let len = sym_def.key_bits() as usize / 8;
                    Self::sensitive_or_random(data, len, &mut rng, seeded.as_mut(), private_key)?
                }
                OwnedPublicParmsAndId::KeyedHash(scheme, _) => {
                    let hash = match scheme {
                        Some(TpmtKeyedHashScheme::Hmac(h))
                        | Some(TpmtKeyedHashScheme::ExclusiveOr(tpm2::TpmsSchemeXor {
                            hash_alg: h,
                            ..
                        })) => *h,
                        None => name_alg,
                    };
                    Self::sensitive_or_random(
                        data,
                        hash.digest_size(),
                        &mut rng,
                        seeded.as_mut(),
                        private_key,
                    )?
                }
                _ => return Err(TpmRc::TYPE.with(Position::parameter(2))),
            };
            // Only Primary Objects have a seeded DRBG to mix the proofs into.
            if let (Some(((sh, sh_len), (eh, eh_len))), Some(state)) =
                (&endorsement_proofs, seeded.as_mut())
            {
                drbg::additional_data(state, &sh[..*sh_len])?;
                drbg::additional_data(state, &eh[..*eh_len])?;
            }
            let seed_len = name_alg.digest_size();
            drbg::fill(&mut rng, seeded.as_mut(), &mut seed[..seed_len])?;
            (key_len, seed_len)
        };
        if let OwnedPublicParmsAndId::Sym(_, unique) | OwnedPublicParmsAndId::KeyedHash(_, unique) =
            parms_and_id
        {
            let (digest, digest_len) =
                self.compute_hash(name_alg, &[&seed[..seed_len], &private_key[..key_len]])?;
            *unique = OwnedDigest::from_bytes(&digest[..digest_len]).map_err(|_| TpmRc::FAILURE)?;
        }
        Ok((seed_len, key_len))
    }

    /// The SYMCIPHER/KEYEDHASH key of `CryptGenerateKeySymmetric()`/`CryptGenerateKeyedHash()`:
    /// the caller's `data` if any, else `len` random bytes from `rand` (`None`: the TPM's DRBG).
    fn sensitive_or_random(
        data: &[u8],
        len: usize,
        rng: &mut RefRng<'_>,
        rand: Option<&mut DrbgState>,
        out: &mut [u8],
    ) -> Result<usize, TpmRc> {
        if data.is_empty() {
            drbg::fill(rng, rand, out.get_mut(..len).ok_or(TpmRc::FAILURE)?)?;
            Ok(len)
        } else {
            out.get_mut(..data.len())
                .ok_or(TpmRc::SIZE.with(Position::parameter(1)))?
                .copy_from_slice(data);
            Ok(data.len())
        }
    }

    /// RSA encryption with the reference code's OAEP (`hash_alg` `Some`) or RSAES-PKCS1-v1_5
    /// (`None`) encoding drawn from the TPM's DRBG, followed by the raw public-key operation of
    /// the crypto provider with the key's `modulus` and public `exponent` (`0` for the default
    /// 65537). Returns `Ok(None)` if the provider rejects the key.
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn reference_rsa_encrypt(
        &mut self,
        hash_alg: Option<TpmiAlgHash>,
        modulus: &[u8],
        exponent: u32,
        label: &[u8],
        message: &[u8],
        out: &mut [u8],
    ) -> Result<Option<usize>, TpmRc> {
        let mut padded = [0u8; 512];
        let padded = padded.get_mut(..modulus.len()).ok_or(TpmRc::FAILURE)?;
        let mut rng = self.context.ref_rng();
        match hash_alg {
            Some(hash) => rsa::oaep_encode(&mut rng, hash, label, message, padded)?,
            None => rsa::rsaes_pkcs1v15_encode(&mut rng, message, padded)?,
        }
        self.crypto()
            .rsa_null_encrypt(modulus, exponent, padded, out)
            .map_err(|_| TpmRc::FAILURE)
    }

    /// An RSASSA-PSS signature with the reference code's salt (drawn from the TPM's DRBG) and
    /// the raw private-key operation of the crypto provider. Returns `Ok(None)` if the provider
    /// rejects the key.
    pub(crate) fn reference_rsa_pss_sign(
        &mut self,
        hash_alg: TpmiAlgHash,
        private_key: &[u8],
        modulus_len: usize,
        digest: &[u8],
        out: &mut [u8],
    ) -> Result<Option<usize>, TpmRc> {
        let mut encoded = [0u8; 512];
        let encoded = encoded.get_mut(..modulus_len).ok_or(TpmRc::FAILURE)?;
        rsa::pss_encode(&mut self.context.ref_rng(), hash_alg, digest, encoded)?;
        self.crypto()
            .rsa_null_decrypt(private_key, encoded, out)
            .map_err(|_| TpmRc::FAILURE)
    }
}
