impl<'a, 'b, C: Crypto, S: NvStorage, T: TpmTimer> CommandHandler<'a, 'b, C, S, T> {
    /// Handles the [TpmCc::Import] (`0x156`) command.
    ///
    /// # Description
    /// This command allows a duplicate key (created off-TPM or on another TPM using [TpmCc::Duplicate](duplicate.rs))
    /// to be imported under a parent key on the current TPM. It returns an encrypted private area (`out_private`)
    /// suitable for loading.
    ///
    /// # Spec Citation
    /// TCG TPM 2.0 Library Specification, Part 3: Commands, Section 13.3 (TPM2_Import).
    ///
    /// # Relationships
    /// - Takes the duplicate blob and seed generated by [TpmCc::Duplicate](duplicate.rs).
    /// - Re-encrypts the key under the parent key (`parent_handle`) so that it can be loaded using [TpmCc::Load](load.rs).
    pub fn import(&mut self, request_response: RequestThenResponse<'_, '_>) -> Result<(), TpmRc> {
        let mut request = request_response;

        let handles = request.try_unmarshal_handles::<Import>()?;
        let [parent_handle_h] = handles;
        check(parent_handle_h, Tpmi::DhObject, Position::handle(1))?;
        let parent_handle = parent_handle_h.0;

        let (session_responses, num_sessions) = self.parse_and_validate_sessions(&mut request)?;

        let (null_name_alg, sym_alg_value_err) = {
            let params_slice = request.remaining_slice();
            let null_name_alg =
                null_name_alg_error::<Tpm2bData>(params_slice, Position::parameter(2));
            let mut slice = params_slice;
            let sym_alg_value_err = Tpm2bData::unmarshal(&mut slice).is_ok()
                && Tpm2bPublic::unmarshal(&mut slice).is_ok()
                && Tpm2bPrivate::unmarshal(&mut slice).is_ok()
                && Tpm2bEncryptedSecret::unmarshal(&mut slice).is_ok()
                && slice
                    .split_first_chunk::<2>()
                    .is_some_and(|(alg_bytes, _)| u16::from_be_bytes(*alg_bytes) > 0x0080);
            (null_name_alg, sym_alg_value_err)
        };
        let cmd = match request.try_unmarshal_command::<Import>(handles) {
            Ok(cmd) => cmd,
            Err(e) => {
                if let Some(rc) = null_name_alg {
                    return Err(rc);
                }
                if sym_alg_value_err {
                    return Err(TpmRc::VALUE.with(Position::parameter(5)));
                }
                return Err(e);
            }
        };
        if request.remaining_bytes() != 0 {
            return Err(TpmRc::SIZE.to_rc());
        }
        if let Some(rc) = null_name_alg {
            return Err(rc);
        }

        let object_public_struct = cmd.object_public.0;

        // 1. Resolve parent object or hierarchy seed and parameters
        let mut parent_seed_val = [0u8; TpmiAlgHash::MAX_DIGEST_BYTES];
        let mut parent_qn_buf = [0u8; Tpm2bName::CAP];
        let parent_info = self.resolve_parent_object_or_hierarchy(
            parent_handle,
            &mut parent_seed_val,
            &mut parent_qn_buf,
            false, // expect_type_error
        )?;

        let parent_obj = match parent_handle_h.handle_type() {
            Some(TpmHt::Transient) => self
                .global_state
                .find_transient_object(parent_handle)
                .cloned()
                .ok_or(TpmRc::REFERENCE_H0)?,
            Some(TpmHt::Persistent) => self
                .context
                .load_persistent_object(self.global_state, parent_handle)
                .map_err(|_| TpmRc::REFERENCE_H0)?,
            _ => return Err(TpmRc::HANDLE.with(Position::handle(1))),
        };

        let parent_symmetric_is_null = match &parent_obj.public.parms_and_id {
            OwnedPublicParmsAndId::Rsa(parms, _) => parms.symmetric.is_none(),
            OwnedPublicParmsAndId::Ecc(parms, _) => parms.symmetric.is_none(),
            _ => true,
        };

        // 2. Validate parameter sizes and attributes (encryptionKey Pos1, symmetricAlg Pos5, objectPublic Pos2, then inSymSeed Pos4)
        let enc_key_len = cmd.encryption_key.as_slice().len();
        match cmd.symmetric_alg {
            None => {
                if enc_key_len > 0 {
                    return Err(TpmRc::SIZE.with(Position::parameter(1)));
                }
            }
            Some(sym_def) => {
                let bits = sym_def.alg.key_bits();
                if bits != 128 && bits != 256 && bits != 192 {
                    return Err(TpmRc::SYMMETRIC.with(Position::parameter(5)));
                }
                if !matches!(
                    sym_def.mode,
                    Some(TpmiAlgSymMode::Cipher(
                        TpmiAlgCipherMode::Cfb
                            | TpmiAlgCipherMode::Ctr
                            | TpmiAlgCipherMode::Ofb
                            | TpmiAlgCipherMode::Cbc
                            | TpmiAlgCipherMode::Ecb
                    ))
                ) {
                    return Err(TpmRc::MODE.with(Position::parameter(5)));
                }
                let inner_key_len = usize::from(bits / 8);
                if enc_key_len > 0 && enc_key_len != inner_key_len {
                    return Err(TpmRc::SIZE.with(Position::parameter(1)));
                }
            }
        }

        let auth_policy_len = object_public_struct.auth_policy.as_slice().len();
        if auth_policy_len != 0
            && let Some(name_alg) = object_public_struct.name_alg
            && auth_policy_len != name_alg.digest_size()
        {
            return Err(TpmRc::SIZE.with(Position::parameter(2)));
        }

        // Check unique/parameter sizes of objectPublic before checking attributes
        match &object_public_struct.parms_and_id {
            PublicParmsAndId::Rsa(rsa_parms, rsa_unique) => {
                let key_size_bytes = usize::from(u16::from(rsa_parms.key_bits)) / 8;
                let unique_len = rsa_unique.as_slice().len();
                if unique_len > 0 && unique_len != key_size_bytes {
                    return Err(TpmRc::SIZE.with(Position::parameter(2)));
                }
            }
            PublicParmsAndId::Ecc(ecc_parms, point) => {
                let param_size = ecc_param_size(ecc_parms.curve_id).unwrap_or(32);
                let x_len = point.x.as_slice().len();
                let y_len = point.y.as_slice().len();
                if (x_len > 0 && x_len != param_size) || (y_len > 0 && y_len != param_size) {
                    return Err(TpmRc::SIZE.with(Position::parameter(2)));
                }
            }
            _ => {}
        }

        let in_sym_seed_bytes = cmd.in_sym_seed.as_slice();
        if !in_sym_seed_bytes.is_empty() {
            if parent_symmetric_is_null {
                return Err(TpmRc::SIZE.with(Position::parameter(4)));
            }
            match &parent_obj.public.parms_and_id {
                OwnedPublicParmsAndId::Rsa(parms, _) => {
                    let expected_size = usize::from(u16::from(parms.key_bits)) / 8;
                    if in_sym_seed_bytes.len() != expected_size {
                        return Err(TpmRc::SIZE.with(Position::parameter(4)));
                    }
                }
                OwnedPublicParmsAndId::Ecc(parms, _) => {
                    let mut slice = in_sym_seed_bytes;
                    let eph_point = TpmsEccPoint::unmarshal(&mut slice)
                        .map_err(|_| TpmRc::ECC_POINT.with(Position::parameter(4)))?;
                    if !slice.is_empty() {
                        return Err(TpmRc::SIZE.with(Position::parameter(4)));
                    }
                    let param_size = ecc_param_size(parms.curve_id)
                        .ok_or(TpmRc::ECC_POINT.with(Position::parameter(4)))?;
                    if eph_point.x.as_slice().len() != param_size
                        || eph_point.y.as_slice().len() != param_size
                    {
                        return Err(TpmRc::ECC_POINT.with(Position::parameter(4)));
                    }
                }
                _ => {
                    return Err(TpmRc::SIZE.with(Position::parameter(4)));
                }
            }
        }

        // 3. Validate semantic attributes on objectPublic (Pos2) and symmetricAlg (Pos1) after size checks
        if cmd.symmetric_alg.is_none()
            && object_public_struct
                .object_attributes
                .contains(TpmaObject::ENCRYPTED_DUPLICATION)
        {
            return Err(TpmRc::ATTRIBUTES.with(Position::parameter(1)));
        }

        if object_public_struct
            .object_attributes
            .intersects(TpmaObject::FIXED_TPM | TpmaObject::FIXED_PARENT)
        {
            return Err(TpmRc::ATTRIBUTES.with(Position::parameter(2)));
        }

        self.validate_public_parameters(&object_public_struct, true)?;

        // 5. Compute object name
        let mut pub_buf = [0u8; TpmtPublic::MAX_SIZE];
        let pub_len = object_public_struct.marshal(&mut pub_buf);
        let object_name = self.compute_name(object_public_struct.name_alg, &pub_buf[..pub_len])?;

        // 6. Recover inner blob from duplicate (removing outer wrapper if present)
        let mut inner_blob = [0u8; Tpm2bPrivate::CAP];
        let inner_blob_len;

        let duplicate_bytes = cmd.duplicate.as_slice();
        let mut seed = [0u8; TpmiAlgHash::MAX_DIGEST_BYTES];
        let mut seed_len = 0;

        if !in_sym_seed_bytes.is_empty() {
            if parent_symmetric_is_null {
                return Err(TpmRc::SIZE.with(Position::parameter(1)));
            }
            let crypto = self.crypto();
            // Decrypt seed using parent private key
            seed_len = match &parent_obj.public.parms_and_id {
                OwnedPublicParmsAndId::Rsa(parms, modulus) => {
                    let parent_name_alg = parent_obj.public.name_alg.ok_or(TpmRc::HASH.to_rc())?;
                    let key = load_rsa_private(
                        crypto,
                        parms,
                        modulus.get_buffer(),
                        &parent_obj.sensitive,
                    )
                    .ok_or(TpmRc::FAILURE)?;
                    let mut decrypted = [0u8; TpmiRsaKeyBits::MAX_PUB_KEY_BYTES];
                    let plaintext = Rsa::decrypt(
                        crypto,
                        &key,
                        RsaEncryptScheme::Oaep {
                            hash: parent_name_alg,
                            label: DUPLICATE_LABEL,
                        },
                        in_sym_seed_bytes,
                        &mut decrypted,
                    )
                    .ok()
                    .flatten()
                    .ok_or(TpmRc::FAILURE)?;
                    let mut writer = Writer::new(&mut seed);
                    writer.bytes(plaintext.as_slice())?;
                    writer.offset()
                }
                OwnedPublicParmsAndId::Ecc(parms, unique) => {
                    let mut slice = in_sym_seed_bytes;
                    let eph_point = TpmsEccPoint::unmarshal(&mut slice)
                        .map_err(|_| TpmRc::ECC_POINT.with(Position::parameter(4)))?;

                    let curve = parms.curve_id;
                    let param_size = ecc_param_size(curve)
                        .ok_or(TpmRc::ECC_POINT.with(Position::parameter(4)))?;

                    let eph_pub = PaddedEccPoint::from_tpms(&eph_point, param_size)
                        .ok_or(TpmRc::ECC_POINT.with(Position::parameter(4)))?;
                    let peer = load_ecc_public(crypto, curve, &eph_pub)
                        .ok_or(TpmRc::ECC_POINT.with(Position::parameter(4)))?;
                    let key = load_ecc_private(crypto, curve, unique, &parent_obj.sensitive)
                        .ok_or(TpmRc::ECC_POINT.with(Position::parameter(4)))?;
                    let ecdh_point = ecc_point_multiply(crypto, &key, &peer, param_size)
                        .ok()
                        .flatten()
                        .ok_or(TpmRc::ECC_POINT.with(Position::parameter(4)))?;

                    let parent_pub = PaddedEccPoint::new(
                        unique.x.get_buffer(),
                        unique.y.get_buffer(),
                        param_size,
                    )
                    .ok_or(TpmRc::VALUE.to_rc())?;

                    let parent_name_alg = parent_obj.public.name_alg.ok_or(TpmRc::HASH.to_rc())?;
                    let digest_size = parent_name_alg.digest_size();

                    kdfe(
                        crypto,
                        parent_name_alg,
                        ecdh_point.x(),
                        c"DUPLICATE",
                        eph_pub.x(),
                        parent_pub.x(),
                        seed.get_mut(..digest_size).ok_or(TpmRc::FAILURE)?,
                    )
                    .map_err(|_| TpmRc::FAILURE)?;
                    digest_size
                }
                _ => return Err(TpmRc::TYPE.with(Position::handle(1))),
            };

            let (mac_size, rest) = duplicate_bytes
                .split_first_chunk::<2>()
                .ok_or(TpmRc::SIZE.to_rc())?;
            let mac_len = usize::from(u16::from_be_bytes(*mac_size));
            let (mac_bytes, encrypted_blob) =
                rest.split_at_checked(mac_len).ok_or(TpmRc::SIZE.to_rc())?;

            // Verify outer integrity HMAC and derive outer symmetric key/IV dynamically
            let sym_key_bits = outer_sym_key_bits(&parent_obj.public.parms_and_id);
            let outer_key_len = usize::from(sym_key_bits / 8);

            let mut sym_key_iv = [0u8; AlgSym::MAX_KEY_BYTES];
            let mut integrity_key = [0u8; TpmiAlgHash::MAX_DIGEST_BYTES];

            // The outer wrapper uses the parent's nameAlg (TPM 2.0 Part 1, "Outer Duplication
            // Wrapper").
            //
            // PORTING: exp used the imported object's nameAlg.
            let parent_name_alg = parent_obj.public.name_alg.ok_or(TpmRc::HASH.to_rc())?;
            let parent_digest_size = parent_name_alg.digest_size();
            let integrity_key = integrity_key
                .get_mut(..parent_digest_size)
                .ok_or(TpmRc::FAILURE)?;
            kdfa(
                crypto,
                parent_name_alg,
                &seed[..seed_len],
                c"INTEGRITY",
                &[],
                &[],
                integrity_key,
            )
            .map_err(|_| TpmRc::FAILURE)?;
            let outer_key = sym_key_iv.get_mut(..outer_key_len).ok_or(TpmRc::FAILURE)?;
            kdfa(
                crypto,
                parent_name_alg,
                &seed[..seed_len],
                c"STORAGE",
                object_name.get_buffer(),
                &[],
                outer_key,
            )
            .map_err(|_| TpmRc::FAILURE)?;

            let (computed_mac_bytes, computed_mac_len) = self
                .compute_hmac(
                    parent_name_alg,
                    integrity_key,
                    &[encrypted_blob, object_name.get_buffer()],
                )
                .map_err(|_| TpmRc::FAILURE)?;

            if mac_len != computed_mac_len
                || !crate::util::constant_time_eq(
                    mac_bytes,
                    computed_mac_bytes
                        .get(..computed_mac_len)
                        .ok_or(TpmRc::FAILURE)?,
                )
            {
                return Err(TpmRc::INTEGRITY.to_rc());
            }

            if encrypted_blob.len() > inner_blob.len() {
                return Err(TpmRc::SIZE.to_rc());
            }
            inner_blob_len = encrypted_blob.len();
            inner_blob[..inner_blob_len].copy_from_slice(encrypted_blob);

            aes_cfb(
                crypto,
                outer_key,
                Direction::Decrypt,
                &mut inner_blob[..inner_blob_len],
            )?;
        } else {
            // No outer wrapper
            if object_public_struct
                .object_attributes
                .contains(TpmaObject::ENCRYPTED_DUPLICATION)
            {
                return Err(TpmRc::ATTRIBUTES.with(Position::parameter(4)));
            }
            if duplicate_bytes.len() > inner_blob.len() {
                return Err(TpmRc::SIZE.to_rc());
            }
            inner_blob_len = duplicate_bytes.len();
            inner_blob[..inner_blob_len].copy_from_slice(duplicate_bytes);
        }

        let mut decrypted_inner = [0u8; Tpm2bPrivate::CAP];
        let sensitive_struct = if let Some(sym_def) = cmd.symmetric_alg {
            let mut inner_key_buf = [0u8; AlgSym::MAX_KEY_BYTES];
            let inner_key_len = usize::from(sym_def.alg.key_bits() / 8);
            let inner_key = inner_key_buf
                .get_mut(..inner_key_len)
                .ok_or(TpmRc::FAILURE)?;

            if enc_key_len > 0 {
                if enc_key_len != inner_key_len {
                    return Err(TpmRc::SIZE.with(Position::parameter(1)));
                }
                inner_key.copy_from_slice(cmd.encryption_key.as_slice());
            } else {
                // Derive inner symmetric wrapper key from the decrypted seed
                if in_sym_seed_bytes.is_empty() {
                    return Err(TpmRc::SIZE.with(Position::parameter(4)));
                }

                let name_alg = object_public_struct.name_alg.ok_or(TpmRc::HASH.to_rc())?;
                kdfa(
                    self.crypto(),
                    name_alg,
                    &seed[..seed_len],
                    c"STORAGE",
                    object_name.get_buffer(),
                    &[],
                    inner_key,
                )
                .map_err(|_| TpmRc::FAILURE)?;
            }

            decrypted_inner[..inner_blob_len].copy_from_slice(&inner_blob[..inner_blob_len]);

            aes_cfb(
                self.crypto(),
                inner_key,
                Direction::Decrypt,
                &mut decrypted_inner[..inner_blob_len],
            )?;

            let decrypted_slice = &decrypted_inner[..inner_blob_len];
            let (inner_integrity_size, after_integrity_size) = decrypted_slice
                .split_first_chunk::<2>()
                .ok_or(TpmRc::SIZE.to_rc())?;
            let inner_integrity_len = usize::from(u16::from_be_bytes(*inner_integrity_size));
            let (inner_mac_bytes, sensitive_2b) = after_integrity_size
                .split_at_checked(inner_integrity_len)
                .ok_or(TpmRc::SIZE.to_rc())?;
            let (sensitive_size_bytes, after_sensitive_size) = sensitive_2b
                .split_first_chunk::<2>()
                .ok_or(TpmRc::SIZE.to_rc())?;
            let sensitive_size = usize::from(u16::from_be_bytes(*sensitive_size_bytes));
            let (sensitive_bytes, _) = after_sensitive_size
                .split_at_checked(sensitive_size)
                .ok_or(TpmRc::SIZE.to_rc())?;

            if inner_integrity_len > 0 {
                let integrity_data_slice = &sensitive_2b[..2 + sensitive_size];
                let name_alg = object_public_struct.name_alg.ok_or(TpmRc::HASH.to_rc())?;
                let (hash_bytes, computed_inner_mac_len) =
                    self.compute_hash(name_alg, &[integrity_data_slice, object_name.get_buffer()])?;

                if computed_inner_mac_len != inner_integrity_len
                    || hash_bytes[..computed_inner_mac_len] != *inner_mac_bytes
                {
                    return Err(TpmRc::INTEGRITY.to_rc());
                }
            }

            let mut slice = sensitive_bytes;
            let sensitive_struct =
                TpmtSensitive::unmarshal(&mut slice).map_err(|_| TpmRc::VALUE.to_rc())?;
            if !slice.is_empty() {
                return Err(TpmRc::SIZE.to_rc());
            }
            sensitive_struct
        } else {
            // No inner wrapper, sensitive area was marshalled inside TPM2B_PRIVATE (with a 2-byte size prefix)
            let inner_slice = &inner_blob[..inner_blob_len];
            let (sensitive_size_bytes, after_size) = inner_slice
                .split_first_chunk::<2>()
                .ok_or(TpmRc::SIZE.to_rc())?;
            let sensitive_size = usize::from(u16::from_be_bytes(*sensitive_size_bytes));
            let (mut slice, _) = after_size
                .split_at_checked(sensitive_size)
                .ok_or(TpmRc::SIZE.to_rc())?;
            let sensitive_struct =
                TpmtSensitive::unmarshal(&mut slice).map_err(|_| TpmRc::VALUE.to_rc())?;
            if !slice.is_empty() {
                return Err(TpmRc::SIZE.to_rc());
            }
            sensitive_struct
        };

        if parent_info.attributes.contains(TpmaObject::FIXED_TPM)
            || matches!(
                parent_handle_h,
                Handle::RH_OWNER | Handle::RH_PLATFORM | Handle::RH_ENDORSEMENT
            )
        {
            self.validate_object_attributes(
                &object_public_struct,
                parent_handle,
                parent_info.hierarchy_val,
                Some(parent_info.attributes),
                true,  // is_import
                false, // allow_null_name_alg
                Position::parameter(2),
            )?;
            self.validate_public_parameters(&object_public_struct, true)?;
        }

        // 6. Public-Private consistency check and import validation
        // Per TCG Part 3 Section 13.3.3: if parent has fixedTPM set, binding/sensitive validation must be checked on import.
        // If parent has fixedTPM clear, binding and secret formatting validation need only be checked when the object is loaded.
        let sensitive = if parent_obj
            .public
            .object_attributes
            .contains(TpmaObject::FIXED_TPM)
        {
            self.validate_and_import_sensitive(
                &object_public_struct,
                &sensitive_struct,
                Position::parameter(3),
                Position::parameter(2),
                true,
            )?
        } else {
            self.validate_and_import_sensitive(
                &object_public_struct,
                &sensitive_struct,
                Position::parameter(3),
                Position::parameter(2),
                true,
            )
            .unwrap_or_else(|_| OwnedSensitiveComposite::from(sensitive_struct.sensitive))
        };

        // 7. Re-encrypt under the new parent key
        let sensitive_create = TpmsSensitiveCreate {
            user_auth: sensitive_struct.auth_value,
            data: Tpm2bSensitiveData::default(),
        };
        let mut private_buf = [0u8; Tpm2bPrivate::CAP];
        let out_private = self.create_and_encrypt_private_area(
            &sensitive_create,
            &sensitive,
            sensitive_struct.seed_value.as_slice(),
            &parent_seed_val[..parent_info.seed_len],
            &object_name,
            false,
            parent_info.name_alg,
            parent_info.sym_bits,
            &mut private_buf,
        )?;

        let rsp = responses::Import { out_private };

        // Write response
        let response = request.into_response();
        self.write_response_all(response, &(), &rsp, &session_responses[..num_sessions])?;
        Ok(())
    }
}
