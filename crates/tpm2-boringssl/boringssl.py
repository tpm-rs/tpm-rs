#!/usr/bin/env python3
"""BoringSSL tooling for tpm2-boringssl. The source is Cargo's checkout of the
`bssl-sys` patched in the workspace's `.cargo/config.toml`, so it's always the
pinned revision.

  boringssl.py build          Build BoringSSL into $BORINGSSL_BUILD_DIR
                              (default: target/boringssl), for $RUST_TARGET
                              (default: the host).
  boringssl.py docs-bindings  Regenerate src/docsrs_bindings.rs.

Needs CMake, a C/C++ compiler, and the `bindgen` CLI (or $BINDGEN). CMake uses
its default generator unless $CMAKE_GENERATOR is set (e.g. to `Ninja`).
"""

import json, os, re, subprocess, sys
from pathlib import Path

CRATE = Path(__file__).resolve().parent
ROOT = CRATE.parents[1]
BINDGEN = os.environ.get("BINDGEN", "bindgen")


def run(*args, **kwargs):
    return subprocess.run(args, cwd=ROOT, check=True, text=True, **kwargs)


def boringssl_src():
    meta = json.loads(run("cargo", "metadata", "--format-version=1", capture_output=True).stdout)
    return next(Path(p["manifest_path"]).parents[2] for p in meta["packages"] if p["name"] == "bssl-sys")


def build():
    out = os.environ.get("BORINGSSL_BUILD_DIR", ROOT / "target/boringssl")
    host = re.search(r"host: (\S+)", run("rustc", "-vV", capture_output=True).stdout)[1]
    target = os.environ.get("RUST_TARGET", host)
    os.environ.setdefault("CMAKE_BUILD_PARALLEL_LEVEL", str(os.cpu_count()))
    run("cmake", "-S", boringssl_src(), "-B", out, "-DCMAKE_BUILD_TYPE=Release",
        "-DBUILD_TESTING=OFF", f"-DRUST_BINDINGS={target}", f"-DBINDGEN_EXECUTABLE={BINDGEN}")
    run("cmake", "--build", out, "--target", "bssl_sys")
    # `bssl-sys` only reruns its build script when the bindings change.
    run("cargo", "clean", "--quiet", "-p", "bssl-sys")


DOCS_TARGET = "x86_64-unknown-linux-gnu"
DOCS_BINDINGS = CRATE / "src/docsrs_bindings.rs"


def docs_bindings():
    """rustdoc doesn't type-check function bodies, so the docs only need the
    items named in signatures, fields, and constants. Starting from no
    bindings, build the docs as docs.rs does, and add the `bssl_sys` items
    rustdoc couldn't find, until the build succeeds."""
    src, items = boringssl_src(), set()
    env = os.environ | {"RUSTC_BOOTSTRAP": "1", "RUSTFLAGS": "--cfg docsrs",
                        "RUSTDOCFLAGS": "--cfg docsrs", "CARGO_TARGET_DIR": str(ROOT / "target/docsrs")}
    while True:
        # BoringSSL's options (`rust/bssl-sys/CMakeLists.txt`), minus layout tests.
        allow = [arg for item in sorted(items) for arg in ("--allowlist-item", f"^{item}$")]
        bindings = items and run(
            BINDGEN, src / "rust/bssl-sys/wrapper.h", "--use-core", "--no-derive-default",
            "--enable-function-attribute-detection", "--default-macro-constant-type=signed",
            "--rustified-enum=point_conversion_form_t", "--no-layout-tests", *allow,
            "--", f"-I{src / 'include'}", f"--target={DOCS_TARGET}", capture_output=True).stdout
        DOCS_BINDINGS.write_text(f"// Generated by `boringssl.py docs-bindings` from BoringSSL's\n"
                                 f"// rust/bssl-sys/wrapper.h (for {DOCS_TARGET}). Don't edit.\n\n{bindings or ''}")
        run("rustfmt", "--edition=2024", DOCS_BINDINGS)
        doc = subprocess.run(["cargo", "doc", "--quiet", "--no-deps", "-p", "tpm2-boringssl",
                              "--target", DOCS_TARGET, "--message-format=short"],
                             cwd=ROOT, env=env, capture_output=True, text=True)
        if doc.returncode == 0:
            return print(f"Wrote {len(items)} items to {DOCS_BINDINGS.relative_to(ROOT)}")
        missing = {a or b for a, b in re.findall(r"bssl_sys::(\w+)|`(\w+)` in module `bssl_sys`", doc.stderr)}
        if missing <= items:
            sys.exit(doc.stderr + "error: the docs build failed for another reason")
        items |= missing


if __name__ == "__main__":
    commands = {"build": build, "docs-bindings": docs_bindings}
    if len(sys.argv) != 2 or sys.argv[1] not in commands:
        sys.exit(__doc__)
    commands[sys.argv[1]]()
