//! [`Symmetric`] and [`SymmetricState`].

use crate::{
    AlgSym,
    crypto::{Block, CipherInput, CryptoError, Direction},
};

/// Symmetric block ciphers, with one associated type per cipher algorithm.
///
/// See the [module documentation](super) for how to implement this trait.
pub trait Symmetric {
    type Aes128: SymmetricState<16>;
    type Aes192: SymmetricState<24>;
    type Aes256: SymmetricState<32>;
    type Sm4_128: SymmetricState<16>;
    type Camellia128: SymmetricState<16>;
    type Camellia192: SymmetricState<24>;
    type Camellia256: SymmetricState<32>;
}

/// Key state for a single symmetric cipher algorithm, with a key of
/// `KEY_SIZE` bytes.
///
/// Backends implement [`init`](Self::init) and one method per cipher mode.
/// The mode methods are only passed valid input, and must update `iv` with
/// the chaining value (`ivOut`) described in [`CipherInput`] (except for the
/// padding of a partial final CFB block, see [`cfb`](Self::cfb)).
pub trait SymmetricState<const KEY_SIZE: usize>: Sized {
    /// Initializes a new cipher key state from `key`.
    fn init(key: &[u8; KEY_SIZE]) -> Result<Self, CryptoError>;

    /// Counter (CTR) mode: XORs `data` in place with the keystream generated
    /// by encrypting successive counter values, starting at `iv`.
    ///
    /// The counter is the entire block, incremented as a 128-bit big-endian
    /// integer (wrapping). A partial final block uses a prefix of its
    /// keystream block. `iv` must be updated to the next counter value. CTR
    /// encryption and decryption are identical.
    fn ctr(&self, iv: &mut Block, data: &mut [u8]) -> Result<(), CryptoError>;

    /// Output Feedback (OFB) mode: XORs `data` in place with the keystream
    /// generated by repeatedly encrypting `iv`.
    ///
    /// `iv` must be updated to the final keystream block (the full block, even
    /// if the final data block is partial). OFB encryption and decryption are
    /// identical.
    fn ofb(&self, iv: &mut Block, data: &mut [u8]) -> Result<(), CryptoError>;

    /// Cipher Block Chaining (CBC) mode: encrypts or decrypts `data` in place,
    /// starting from `iv`.
    ///
    /// `iv` must be updated to the final ciphertext block.
    fn cbc(&self, dir: Direction, iv: &mut Block, data: &mut [Block]) -> Result<(), CryptoError>;

    /// Cipher Feedback (CFB) mode, with full-block (128-bit) feedback:
    /// encrypts or decrypts `data` in place, starting from `iv`.
    ///
    /// A partial final block uses a prefix of its keystream block.
    ///
    /// `iv` must be updated to the final ciphertext block. If that block is
    /// partial (`n` bytes), only `iv[..n]` must hold its ciphertext. The
    /// remaining bytes may be left in any state (most libraries leave the rest
    /// of the keystream there), as [`default_crypt`] zeroes them to produce
    /// the TPM's chaining value.
    fn cfb(&self, dir: Direction, iv: &mut Block, data: &mut [u8]) -> Result<(), CryptoError>;

    /// Electronic Codebook (ECB) mode: encrypts or decrypts each block of
    /// `data` in place, independently.
    fn ecb(&self, dir: Direction, data: &mut [Block]) -> Result<(), CryptoError>;

    /// Encrypts or decrypts `input` in place, updating its IV with the
    /// chaining value described in [`CipherInput`].
    ///
    /// Defaults to [`default_crypt`].
    fn crypt(&self, dir: Direction, input: CipherInput<'_>) -> Result<(), CryptoError> {
        default_crypt(self, dir, input)
    }

    /// Encrypts or decrypts `input` in place with `key` in one shot, updating
    /// its IV with the chaining value described in [`CipherInput`].
    #[inline(never)]
    fn crypt_once(
        key: &[u8; KEY_SIZE],
        dir: Direction,
        input: CipherInput<'_>,
    ) -> Result<(), CryptoError> {
        // Use the state inside the `Result`: moving it out would copy it.
        match &Self::init(key) {
            Ok(state) => state.crypt(dir, input),
            Err(e) => Err(*e),
        }
    }
}

impl<const KEY_SIZE: usize> SymmetricState<KEY_SIZE> for ! {
    fn init(_: &[u8; KEY_SIZE]) -> Result<Self, CryptoError> {
        Err(CryptoError::Unsupported)
    }
    fn ctr(&self, _: &mut Block, _: &mut [u8]) -> Result<(), CryptoError> {
        match *self {}
    }
    fn ofb(&self, _: &mut Block, _: &mut [u8]) -> Result<(), CryptoError> {
        match *self {}
    }
    fn cbc(&self, _: Direction, _: &mut Block, _: &mut [Block]) -> Result<(), CryptoError> {
        match *self {}
    }
    fn cfb(&self, _: Direction, _: &mut Block, _: &mut [u8]) -> Result<(), CryptoError> {
        match *self {}
    }
    fn ecb(&self, _: Direction, _: &mut [Block]) -> Result<(), CryptoError> {
        match *self {}
    }
}

/// The default implementation of [`SymmetricState::crypt`].
///
/// Dispatches to the cipher mode methods (never to
/// [`crypt`](SymmetricState::crypt) itself), and zero pads the chaining value
/// after a partial final CFB block.
pub fn default_crypt<S: SymmetricState<K>, const K: usize>(
    state: &S,
    dir: Direction,
    input: CipherInput<'_>,
) -> Result<(), CryptoError> {
    match input {
        #[cfg(feature = "ctr")]
        CipherInput::Ctr(iv, data) => state.ctr(iv, data),
        #[cfg(feature = "ofb")]
        CipherInput::Ofb(iv, data) => state.ofb(iv, data),
        #[cfg(feature = "cbc")]
        CipherInput::Cbc(iv, data) => state.cbc(dir, iv, data),
        CipherInput::Cfb(iv, data) => {
            state.cfb(dir, iv, data)?;
            // The TPM zero pads the chaining value after a partial final block.
            let partial = data.len() % AlgSym::BLOCK_SIZE;
            if partial != 0 {
                iv[partial..].fill(0);
            }
            Ok(())
        }
        #[cfg(feature = "ecb")]
        CipherInput::Ecb(data) => state.ecb(dir, data),
    }
}
