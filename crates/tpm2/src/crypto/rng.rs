//! TPM 2.0 Random Number Generator (RNG) Abstractions
//!
//! This module defines the cryptographic traits required for random number generation in TPM 2.0,
//! including TRNG (True Random Number Generator) and DRBG (Deterministic Random Bit Generator)
//! operations:
//!   - [`Rng`] is a stateful random bit generator (`fill_bytes` / `reseed`). It is used for the
//!     platform RNG ([`TpmPlatform`](crate::platform::TpmPlatform)) and for deterministic
//!     primary-key generation.
//!   - [`Random`] is the factory interface creating [`Rng`] instances from a cryptographic
//!     backend.
//!
//! The provider CSPRNG used by the TPM engine for nonces, seeds, and keys is part of
//! [`CryptoProvider`](super::CryptoProvider) ([`get_random`](super::CryptoProvider::get_random)
//! and [`stir_random`](super::CryptoProvider::stir_random)).
//!
//! ### Provider Abstraction
//!
//! Similar to other cryptographic components in `tpm-rs`, these operations are defined as traits
//! rather than concrete structs. This allows the core library to remain independent of the
//! underlying cryptographic backend (e.g., RustCrypto, BoringSSL).
//!
//! Users can implement these traits for their specific hardware or software stack and provide
//! the implementation via the [`CryptoProvider`](super::CryptoProvider) trait.
//!
//! ### Error Handling
//!
//! All operations return [`CryptoError`] to indicate failure: [`CryptoError::Internal`] for
//! failures of the entropy source or generator (which put the TPM into failure mode), and
//! [`CryptoError::Unsupported`] for unimplemented factories.
use super::CryptoError;

/// Stateful random bit generator used for both the global TPM DRBG
/// and deterministic primary-key generation (`TPM2_CreatePrimary`).
pub trait Rng {
    /// Fills `dest` with generated bytes.
    fn fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), CryptoError>;

    /// Deterministically mixes `data` into the DRBG state.
    ///
    /// Used for `TPM2_StirRandom` on the global RNG, and for mixing `name`,
    /// `additional_data`, and hierarchy proof values into a seeded RNG in
    /// `TPM2_CreatePrimary`.
    fn reseed(&mut self, data: &[u8]) -> Result<(), CryptoError>;
}

impl Rng for ! {
    fn fill_bytes(&mut self, _: &mut [u8]) -> Result<(), CryptoError> {
        match *self {}
    }

    fn reseed(&mut self, _: &[u8]) -> Result<(), CryptoError> {
        match *self {}
    }
}

/// Cryptographic RNG factory interface for TPM implementations and clients.
#[allow(unused_variables)]
pub trait Random {
    type Rng: Rng;

    /// Instantiates a new RNG seeded from hardware/platform entropy
    /// (used to initialize the global TPM RNG).
    fn rng(&self) -> Result<Self::Rng, CryptoError> {
        Err(CryptoError::Unsupported)
    }

    /// Instantiates a deterministic RNG from `seed`
    /// (used for `TPM2_CreatePrimary`).
    fn rng_seeded(&self, seed: &[u8]) -> Result<Self::Rng, CryptoError> {
        Err(CryptoError::Unsupported)
    }
}
