//! Object creation and random asymmetric operations with the `reference-rng` feature.
//!
//! These are the counterparts of the reference code's `CryptCreateObject()`,
//! `CryptEccNewKeyPair()`, `TpmEcc_SignEcdsa()` (with `rand = NULL`) and the randomized RSA
//! encodings, on the reference's own C code linked by [`crate::reference_rng`]: they draw exactly
//! the random values the C reference TPMs draw, in the same order, from the same `RAND_STATE`
//! (the TPM's DRBG, or the DRBG seeded from a hierarchy's Primary Seed for Primary Objects). The
//! raw RSA operations on the padded blocks use the crypto backend.

use crate::Platform;
use tpm2::Marshal;
use tpm2::crypto::{Crypto, RsaPublicKey};
use tpm2::errors::{Position, TpmRc};
use tpm2::{
    Alg, Tpm2bPublicKeyRsa, TpmEccCurve, TpmaObject, TpmiAlgHash, TpmiRsaKeyBits, TpmsRsaParms,
    TpmtKeyedHashScheme, TpmtPublic,
};

use crate::engine::DrbgState;
use crate::handler::CommandHandler;
use crate::owned::{OwnedDigest, OwnedEccPoint, OwnedPublicParmsAndId, OwnedTpm2b};
use crate::reference_rng::{RefRng, drbg, ecc, rsa};

/// `PRIMARY_OBJECT_CREATION`: the DRBG purpose of Primary Objects, with its terminating NUL.
const PRIMARY_OBJECT_CREATION: &[u8] = b"Primary Object Creation\0";

/// The Primary Seed context of a Primary Object being created.
pub(crate) struct PrimaryCreation<'p> {
    /// The hierarchy's Primary Seed (`HierarchyGetPrimarySeed()`).
    pub seed: &'p [u8],
    /// Whether the object is created in the endorsement hierarchy (`epsHierarchy`).
    pub endorsement: bool,
}

impl<'b, C: Crypto, P: Platform<Crypto = C>> CommandHandler<'b, P> {
    /// `CryptEccSign()` with the TPM's DRBG for the scheme `scheme` (ECDSA, SM2 or EC-Schnorr)
    /// and its hash `hash`: signs `digest` with the private scalar `d` (big-endian) on `curve`,
    /// writing `r` and `s` (each padded to the order size) into `r_out`/`s_out`. Returns the
    /// order size.
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn reference_ecc_sign(
        &mut self,
        scheme: tpm2::Alg,
        hash: tpm2::TpmiAlgHash,
        curve: TpmEccCurve,
        d: &[u8],
        digest: &[u8],
        r_out: &mut [u8],
        s_out: &mut [u8],
    ) -> Result<usize, TpmRc> {
        ecc::sign(
            &mut self.context.ref_rng(),
            None,
            scheme,
            hash,
            curve,
            d,
            digest,
            r_out,
            s_out,
        )
    }

    /// `CryptEccNewKeyPair()`: an ephemeral key pair from the TPM's DRBG (ECDH_KeyGen and
    /// `CryptSecretEncrypt()` for ECC keys). Writes `d` (padded to the coordinate size) into
    /// `d_out` and `x || y` into `q_out`, and returns the coordinate size.
    pub(crate) fn reference_ecc_new_key_pair(
        &mut self,
        curve: TpmEccCurve,
        d_out: &mut [u8],
        q_out: &mut [u8],
    ) -> Result<usize, TpmRc> {
        // `CryptEccNewKeyPair()` tests ECDH first (no random values).
        self.do_self_test(tpm2::Alg::ECDH)?;
        ecc::new_key_pair(&mut self.context.ref_rng(), curve, d_out, q_out)
    }

    /// The FIPS pairwise consistency test of `CryptEccGenerateKey()` for a signing key that was
    /// not generated by [`Self::reference_create_object`] (a Derived Object): signs a random
    /// digest (`min(key size, 64)` bytes) with ECDSA, both drawn from the TPM's DRBG. Only the
    /// random draws matter for the TPM's state.
    pub(crate) fn reference_ecc_pairwise_test(
        &mut self,
        curve: TpmEccCurve,
        d: &[u8],
    ) -> Result<(), TpmRc> {
        ecc::pairwise_test(&mut self.context.ref_rng(), curve, d)
    }

    /// `CryptCreateObject()`: generates the sensitive area of a new ordinary object (from the
    /// TPM's DRBG) or Primary Object (`primary`, from `DRBG_InstantiateSeeded(seed,
    /// PRIMARY_OBJECT_CREATION, template Name, inSensitive.data)`).
    ///
    /// Generates the key (RSA, ECC, or a TPM-generated SYMCIPHER/KEYEDHASH key when no data is
    /// supplied or `sensitiveDataOrigin` is SET), mixes in the endorsement hierarchy proofs for
    /// endorsement Primary Objects, draws the `seedValue` (one `nameAlg` digest) and computes the
    /// public `unique` field. Writes the private key (the prime p of an RSA key, as
    /// [`crate::handler::rsa_private_prime`] normalizes it) to `private_key` and the `seedValue` to `seed`, and returns `(seed length, key length)`.
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn reference_create_object(
        &mut self,
        primary: Option<PrimaryCreation<'_>>,
        template: &TpmtPublic,
        sensitive_data: &[u8],
        parms_and_id: &mut OwnedPublicParmsAndId,
        private_key: &mut [u8],
        seed: &mut [u8; 64],
    ) -> Result<(usize, usize), TpmRc> {
        let name_alg = template
            .name_alg
            .ok_or(TpmRc::HASH.with(Position::parameter(2)))?;
        let attributes = template.object_attributes;
        let mut seeded: Option<DrbgState> = match &primary {
            Some(p) => {
                let mut buf = [0u8; tpm2::TpmtPublic::MAX_SIZE];
                let len = template.marshal(&mut buf);
                let template_name = self.compute_name(Some(name_alg), &buf[..len])?;
                Some(drbg::instantiate_seeded(
                    p.seed,
                    PRIMARY_OBJECT_CREATION,
                    template_name.get_buffer(),
                    sensitive_data,
                )?)
            }
            None => None,
        };
        let data = if attributes.contains(TpmaObject::SENSITIVE_DATA_ORIGIN) {
            &[][..]
        } else {
            sensitive_data
        };
        let sign = attributes.contains(TpmaObject::SIGN_ENCRYPT);
        // `CryptEccGenerateKey()` starts with the ECDSA self test ("ECDSA is used to verify each
        // key"), which draws from the TPM's DRBG before the key does.
        if matches!(parms_and_id, OwnedPublicParmsAndId::Ecc(..)) {
            self.do_self_test(tpm2::Alg::ECDSA)?;
        }
        // `CryptoMlkem_GenerateKey()`/`CryptoMldsa_GenerateKey()` test the algorithm before they
        // draw the seed.
        self.pqc_key_generation_self_test(parms_and_id)?;

        // `DRBG_AdditionalData()` input of endorsement Primary Objects: shProof and ehProof.
        let endorsement_proofs = match &primary {
            Some(p) if p.endorsement => {
                let state = &self.context.state;
                let (mut sh, mut eh) = ([0u8; 64], [0u8; 64]);
                let sh_len = usize::from(state.nv.persistent.sh_proof_size).min(64);
                let eh_len = usize::from(state.nv.persistent.eh_proof_size).min(64);
                sh[..sh_len].copy_from_slice(&state.nv.persistent.sh_proof[..sh_len]);
                eh[..eh_len].copy_from_slice(&state.nv.persistent.eh_proof[..eh_len]);
                Some(((sh, sh_len), (eh, eh_len)))
            }
            _ => None,
        };

        // The key and `seedValue` are drawn from the Primary Object DRBG (`seeded`) or the TPM's
        // DRBG (`None`); the pairwise test of an ECC signing key always draws from the TPM's DRBG.
        let (key_len, seed_len) = {
            let engine = &mut *self.context;
            let mut rng = RefRng {
                drbg: Some(&mut engine.state.nv.orderly.drbg_state),
                entropy: Some(engine.platform.rng()),
            };
            let key_len = match parms_and_id {
                OwnedPublicParmsAndId::Rsa(parms, unique) => {
                    let n_len = usize::from(parms.key_bits.as_u16()) / 8;
                    let mut n = [0u8; 512];
                    let mut p = [0u8; 256];
                    let n = n.get_mut(..n_len).ok_or(TpmRc::FAILURE)?;
                    let p = p.get_mut(..n_len / 2).ok_or(TpmRc::FAILURE)?;
                    rsa::generate_key(
                        &mut rng,
                        seeded.as_mut(),
                        parms.key_bits.as_u16(),
                        parms.exponent,
                        sign,
                        n,
                        p,
                    )?;
                    *unique = OwnedTpm2b::from_bytes(n).map_err(|_| TpmRc::FAILURE)?;
                    let key = crate::handler::rsa_private_key::<C>(parms, n, p)
                        .map_err(|_| TpmRc::FAILURE)?
                        .ok_or(TpmRc::FAILURE)?;
                    crate::handler::rsa_private_prime(&key, private_key)
                        .map_err(|_| TpmRc::FAILURE)?
                }
                OwnedPublicParmsAndId::Ecc(parms, point) => {
                    let mut q = [0u8; 2 * TpmEccCurve::MAX_ECC_KEY_BYTES];
                    let len = ecc::generate_key(
                        &mut rng,
                        seeded.as_mut(),
                        parms.curve_id,
                        sign,
                        private_key,
                        &mut q,
                    )?;
                    *point = OwnedEccPoint {
                        x: OwnedTpm2b::from_bytes(&q[..len]).map_err(|_| TpmRc::FAILURE)?,
                        y: OwnedTpm2b::from_bytes(&q[len..2 * len]).map_err(|_| TpmRc::FAILURE)?,
                    };
                    len
                }
                OwnedPublicParmsAndId::Sym(sym_def, _) => {
                    let len = sym_def.key_bits() as usize / 8;
                    Self::sensitive_or_random(data, len, &mut rng, seeded.as_mut(), private_key)?
                }
                // `CryptoMlkem_GenerateKey()`/`CryptoMldsa_GenerateKey()`: the seed is drawn from
                // the DRBG, and the public key derived from it.
                OwnedPublicParmsAndId::Mlkem(parms, unique) => {
                    let mut seed = [0u8; tpm2::TpmiMlkemParms::PRIV_KEY_BYTES];
                    drbg::fill(&mut rng, seeded.as_mut(), &mut seed)?;
                    *unique = mlkem_public_key::<C, _>(parms.parameter_set, &seed)?;
                    private_key
                        .get_mut(..seed.len())
                        .ok_or(TpmRc::FAILURE)?
                        .copy_from_slice(&seed);
                    seed.len()
                }
                OwnedPublicParmsAndId::Mldsa(
                    tpm2::TpmsMldsaParms { parameter_set, .. },
                    unique,
                )
                | OwnedPublicParmsAndId::HashMldsa(
                    tpm2::TpmsHashMldsaParms { parameter_set, .. },
                    unique,
                ) => {
                    let mut seed = [0u8; tpm2::TpmiMldsaParms::PRIV_KEY_BYTES];
                    drbg::fill(&mut rng, seeded.as_mut(), &mut seed)?;
                    *unique = mldsa_public_key::<C, _>(*parameter_set, &seed)?;
                    private_key
                        .get_mut(..seed.len())
                        .ok_or(TpmRc::FAILURE)?
                        .copy_from_slice(&seed);
                    seed.len()
                }
                OwnedPublicParmsAndId::KeyedHash(scheme, _) => {
                    let hash = match scheme {
                        Some(TpmtKeyedHashScheme::Hmac(h))
                        | Some(TpmtKeyedHashScheme::ExclusiveOr(tpm2::TpmsSchemeXor {
                            hash_alg: h,
                            ..
                        })) => *h,
                        None => name_alg,
                    };
                    Self::sensitive_or_random(
                        data,
                        hash.digest_size(),
                        &mut rng,
                        seeded.as_mut(),
                        private_key,
                    )?
                }
            };
            // Only Primary Objects have a seeded DRBG to mix the proofs into.
            if let (Some(((sh, sh_len), (eh, eh_len))), Some(state)) =
                (&endorsement_proofs, seeded.as_mut())
            {
                drbg::additional_data(state, &sh[..*sh_len])?;
                drbg::additional_data(state, &eh[..*eh_len])?;
            }
            let seed_len = name_alg.digest_size();
            drbg::fill(&mut rng, seeded.as_mut(), &mut seed[..seed_len])?;
            (key_len, seed_len)
        };
        if let OwnedPublicParmsAndId::Sym(_, unique) | OwnedPublicParmsAndId::KeyedHash(_, unique) =
            parms_and_id
        {
            let (digest, digest_len) =
                self.compute_hash(name_alg, &[&seed[..seed_len], &private_key[..key_len]])?;
            *unique = OwnedDigest::from_bytes(&digest[..digest_len]).map_err(|_| TpmRc::FAILURE)?;
        }
        Ok((seed_len, key_len))
    }

    /// The SYMCIPHER/KEYEDHASH key of `CryptGenerateKeySymmetric()`/`CryptGenerateKeyedHash()`:
    /// the caller's `data` if any, else `len` random bytes from `rand` (`None`: the TPM's DRBG).
    fn sensitive_or_random(
        data: &[u8],
        len: usize,
        rng: &mut RefRng<'_>,
        rand: Option<&mut DrbgState>,
        out: &mut [u8],
    ) -> Result<usize, TpmRc> {
        if data.is_empty() {
            drbg::fill(rng, rand, out.get_mut(..len).ok_or(TpmRc::FAILURE)?)?;
            Ok(len)
        } else {
            out.get_mut(..data.len())
                .ok_or(TpmRc::SIZE.with(Position::parameter(1)))?
                .copy_from_slice(data);
            Ok(data.len())
        }
    }

    /// RSA encryption with the reference code's OAEP (`hash_alg` `Some`) or RSAES-PKCS1-v1_5
    /// (`None`) encoding drawn from the TPM's DRBG, followed by the raw public-key operation of
    /// the crypto backend with the key's `modulus` (whose size is the key size) and public
    /// `exponent` (`0` for the default 65537). Returns `Ok(None)` if the backend rejects the key.
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn reference_rsa_encrypt(
        &mut self,
        hash_alg: Option<TpmiAlgHash>,
        modulus: &[u8],
        exponent: u32,
        label: &[u8],
        message: &[u8],
        out: &mut [u8],
    ) -> Result<Option<usize>, TpmRc> {
        let mut padded = [0u8; 512];
        let padded = padded.get_mut(..modulus.len()).ok_or(TpmRc::FAILURE)?;
        let mut rng = self.context.ref_rng();
        match hash_alg {
            Some(hash) => rsa::oaep_encode(&mut rng, hash, label, message, padded)?,
            None => rsa::rsaes_pkcs1v15_encode(&mut rng, message, padded)?,
        }
        let public = u16::try_from(modulus.len() * 8)
            .ok()
            .and_then(TpmiRsaKeyBits::new)
            .zip(Tpm2bPublicKeyRsa::new(modulus))
            .map(|(bits, modulus)| RsaPublicKey::<C>::load(bits, exponent, modulus))
            .transpose()
            .map_err(|_| TpmRc::FAILURE)?
            .flatten();
        let Some(public) = public else {
            return Ok(None);
        };
        crate::rsa::rsa_encrypt::<C>(
            &mut self.context.crypto_rng,
            &public,
            Alg::NULL,
            Alg::NULL,
            &[],
            padded,
            out,
        )
        .map_err(|_| TpmRc::FAILURE)
    }

    /// An RSASSA-PSS signature with the reference code's salt (drawn from the TPM's DRBG) and
    /// the raw private-key operation of the crypto backend, with the RSA key of the parameters
    /// `parms`, the public `modulus` and the private `prime` (as
    /// [`crate::handler::rsa_private_key`] loads it). Returns `Ok(None)` if the backend rejects
    /// the key.
    pub(crate) fn reference_rsa_pss_sign(
        &mut self,
        hash_alg: TpmiAlgHash,
        parms: &TpmsRsaParms,
        modulus: &[u8],
        prime: &[u8],
        digest: &[u8],
        out: &mut [u8],
    ) -> Result<Option<usize>, TpmRc> {
        let mut encoded = [0u8; 512];
        let encoded = encoded.get_mut(..modulus.len()).ok_or(TpmRc::FAILURE)?;
        rsa::pss_encode(&mut self.context.ref_rng(), hash_alg, digest, encoded)?;
        let Some(key) = crate::handler::rsa_private_key::<C>(parms, modulus, prime)
            .map_err(|_| TpmRc::FAILURE)?
        else {
            return Ok(None);
        };
        crate::rsa::rsa_decrypt::<C>(
            &mut self.context.crypto_rng,
            &key,
            Alg::NULL,
            Alg::NULL,
            &[],
            encoded,
            out,
        )
        .map_err(|_| TpmRc::FAILURE)
    }
}

/// The public key of the ML-KEM key with the parameter set `parms` and the seed `seed`
/// ([`tpm2::crypto::MlkemPrivateKey::expand`]; `TPM_RC_PARMS` if the backend cannot derive it).
#[cfg(feature = "mlkem")]
fn mlkem_public_key<C: Crypto, const N: usize>(
    parms: tpm2::TpmiMlkemParms,
    seed: &[u8],
) -> Result<OwnedTpm2b<N>, TpmRc> {
    let seed = tpm2::Tpm2bPrivateKeyMlkem::new(seed).ok_or(TpmRc::FAILURE)?;
    let key = tpm2::crypto::MlkemPrivateKey::<C>::expand(parms, seed)
        .ok()
        .flatten()
        .ok_or(TpmRc::PARMS.to_rc())?;
    let mut buf = [0u8; tpm2::TpmiMlkemParms::MAX_PUB_KEY_BYTES];
    let public = key.public(&mut buf).map_err(|_| TpmRc::PARMS.to_rc())?;
    OwnedTpm2b::from_bytes(public.as_slice()).map_err(|_| TpmRc::FAILURE)
}

/// Without the `mlkem` feature, ML-KEM keys are not implemented.
#[cfg(not(feature = "mlkem"))]
#[allow(clippy::extra_unused_type_parameters)] // The signature of the `mlkem` build.
fn mlkem_public_key<C: Crypto, const N: usize>(
    _parms: tpm2::TpmiMlkemParms,
    _seed: &[u8],
) -> Result<OwnedTpm2b<N>, TpmRc> {
    Err(TpmRc::PARMS.to_rc())
}

/// The public key of the ML-DSA key with the parameter set `parms` and the seed `seed`
/// ([`tpm2::crypto::MldsaPrivateKey::expand`]; `TPM_RC_PARMS` if the backend cannot derive it).
#[cfg(feature = "mldsa")]
fn mldsa_public_key<C: Crypto, const N: usize>(
    parms: tpm2::TpmiMldsaParms,
    seed: &[u8],
) -> Result<OwnedTpm2b<N>, TpmRc> {
    let seed = tpm2::Tpm2bPrivateKeyMldsa::new(seed).ok_or(TpmRc::FAILURE)?;
    let key = tpm2::crypto::MldsaPrivateKey::<C>::expand(parms, seed)
        .ok()
        .flatten()
        .ok_or(TpmRc::PARMS.to_rc())?;
    let mut buf = [0u8; tpm2::TpmiMldsaParms::MAX_PUB_KEY_BYTES];
    let public = key.public(&mut buf).map_err(|_| TpmRc::PARMS.to_rc())?;
    OwnedTpm2b::from_bytes(public.as_slice()).map_err(|_| TpmRc::FAILURE)
}

/// Without the `mldsa` feature, ML-DSA keys are not implemented.
#[cfg(not(feature = "mldsa"))]
#[allow(clippy::extra_unused_type_parameters)] // The signature of the `mldsa` build.
fn mldsa_public_key<C: Crypto, const N: usize>(
    _parms: tpm2::TpmiMldsaParms,
    _seed: &[u8],
) -> Result<OwnedTpm2b<N>, TpmRc> {
    Err(TpmRc::PARMS.to_rc())
}
