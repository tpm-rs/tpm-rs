//! TPM2_Create of a storage key under a parent in the NULL hierarchy: the
//! parent's hierarchy does not restrict *fixedTPM*/*fixedParent* (only the
//! parent's *fixedTPM* does), so the creation reaches the scheme checks of a
//! non-duplicable storage key.

use crate::_common::{rc_of, rc_p};
use testing::tpm::Tpm;
use tpm2::errors::TpmRc;

/// `TPM2_CreatePrimary` in the NULL hierarchy of an ECC NIST P-256 storage key
/// (SHA256 Name, AES-128-CFB, *fixedTPM* | *fixedParent*), with a fixed
/// `unique`.
const CREATE_PRIMARY_NULL_STORAGE: [u8; 99] = [
    0x80, 0x02, 0x00, 0x00, 0x00, 0x63, 0x00, 0x00, 0x01, 0x31, 0x40, 0x00, 0x00, 0x07, 0x00, 0x00,
    0x00, 0x09, 0x40, 0x00, 0x00, 0x09, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x3a, 0x00, 0x23, 0x00, 0x0b, 0x00, 0x03, 0x00, 0x72, 0x00, 0x00, 0x00, 0x06, 0x00,
    0x80, 0x00, 0x43, 0x00, 0x10, 0x00, 0x03, 0x00, 0x10, 0x00, 0x20, 0x01, 0x01, 0x01, 0x01, 0x01,
    0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01,
    0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00,
];

/// `TPM2_Create` under the transient handle 0x80000000 of an ECC NIST P-256
/// storage key with a SHA384 Name (*fixedTPM* | *fixedParent*).
const CREATE_SHA384_STORAGE_CHILD: [u8; 67] = [
    0x80, 0x02, 0x00, 0x00, 0x00, 0x43, 0x00, 0x00, 0x01, 0x53, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x09, 0x40, 0x00, 0x00, 0x09, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x1a, 0x00, 0x23, 0x00, 0x0c, 0x00, 0x03, 0x00, 0x72, 0x00, 0x00, 0x00, 0x06, 0x00,
    0x80, 0x00, 0x43, 0x00, 0x10, 0x00, 0x03, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00,
];

/// A non-duplicable storage child of a *fixedTPM* parent in the NULL hierarchy
/// passes the attribute checks (TPM 2.0 Part 2, TPMA_OBJECT Bit[1] fixedTPM,
/// "Creation": "If *fixedTPM* is SET in the object's parent, then *fixedTPM*
/// shall equal *fixedParent* in *template.*") and is rejected because its
/// nameAlg differs from its parent's (`TPM_RC_HASH` on `inPublic`, as in the
/// reference's `SchemeChecks()`: "If this parent is not duplicable, then the
/// symmetric algorithms (encryption and hash) must match those of its parent").
#[test]
fn null_hierarchy_parent_allows_fixed_tpm_children() {
    let mut tpm = Tpm::new();
    let rsp = tpm.send_command(0, &CREATE_PRIMARY_NULL_STORAGE);
    assert_eq!(rc_of(&rsp), 0, "CreatePrimary: {rsp:02x?}");
    assert_eq!(&rsp[10..14], &[0x80, 0, 0, 0]);
    assert_eq!(
        rc_of(&tpm.send_command(0, &CREATE_SHA384_STORAGE_CHILD)),
        rc_p(TpmRc::HASH, 2)
    );
}
